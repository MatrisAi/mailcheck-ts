#!/usr/bin/env node
/**
 * Regenerate src/tlds.ts from IANA's root zone list
 * (https://data.iana.org/TLD/tlds-alpha-by-domain.txt). Run by hand; the
 * file is committed so the package never fetches anything at runtime.
 *
 * Internationalised TLDs (`xn--...`) are left out: `suggest()` never touches
 * an internationalised domain.
 */
import { writeFileSync } from "node:fs";

const SOURCE = "https://data.iana.org/TLD/tlds-alpha-by-domain.txt";
const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
const text = await response.text();
const lines = text.split("\n").map((line) => line.trim());
const version = (lines[0] ?? "").replace(/^#\s*/, "");
const tlds = lines
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => line.toLowerCase())
  .filter((tld) => /^[a-z]{2,63}$/.test(tld));
if (tlds.length < 1000) throw new Error(`only ${tlds.length} TLDs parsed; refusing to write a short list`);

const rows = [];
for (let i = 0; i < tlds.length; i += 16) rows.push(`  "${tlds.slice(i, i + 16).join(" ")}",`);

const out = `/**
 * Every ASCII top-level domain in the root zone, from IANA
 * (${SOURCE}, ${version}).
 * Generated by scripts/update-tlds.mjs; do not edit by hand.
 *
 * Used for one decision only: a domain whose last label is a REAL TLD is
 * never "corrected" to another TLD (\`company.co\` stays \`.co\`).
 */
const TLD_TEXT = [
${rows.join("\n")}
].join(" ");

export const IANA_TLDS: ReadonlySet<string> = new Set(TLD_TEXT.split(" "));

/** True when \`label\` (lower case, no dot) is a top-level domain in the root zone. */
export function isRealTld(label: string): boolean {
  return IANA_TLDS.has(label);
}
`;
writeFileSync(new URL("../src/tlds.ts", import.meta.url), out);
console.log(`wrote ${tlds.length} TLDs (${version})`);
