#!/usr/bin/env node
/**
 * Regenerate src/disposable-list.ts from the disposable-email-domains project
 * (https://github.com/disposable-email-domains/disposable-email-domains,
 * `disposable_email_blocklist.conf`, CC0 1.0). Run by hand, review the diff,
 * commit it: the package never fetches anything at runtime.
 *
 *   pnpm run update-disposable              regenerate the module
 *   pnpm run update-disposable --review     also print the review table below
 *   pnpm run update-disposable --review 50000   with another Tranco cut-off
 *
 * Normalised (trimmed, lower case, no comments or blanks, ASCII host names
 * only), deduplicated and sorted, so the diff of an update shows exactly the
 * domains that moved. Left out and named: an entry that is one of our
 * providers or a parent of one, and an entry that is (or is below) a
 * reviewed real company in NEVER_DISPOSABLE (src/disposable-policy.ts).
 *
 * `--review` lists every entry that ranks in the Tranco top N (default
 * 100,000; the list is downloaded at run time, never committed) AND publishes
 * its own MX: a popular domain that receives mail is where a wrong
 * "disposable" would refuse real people. Each row must be decided by hand:
 * keep it (a real throwaway service; exact name only, which is the default)
 * or move it to NEVER_DISPOSABLE (a real mailbox provider or company).
 *
 * `--wildcards` asks DNS for an MX at a random label below EVERY entry and
 * lists those that answer (a wildcard MX), with their Tranco rank: the
 * evidence for WILDCARD_DISPOSABLE, the reviewed services whose subdomains
 * are disposable too. A hosting or dynamic DNS domain with a wildcard MX
 * stays out of that set: its subdomains are its customers'.
 * Neither mode sends any email.
 */
import { writeFileSync } from "node:fs";
import { createJiti } from "jiti";

const SOURCE = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
const jiti = createJiti(import.meta.url);
const { PROVIDER_DOMAINS } = await jiti.import(new URL("../src/providers.ts", import.meta.url).href);
const { NEVER_DISPOSABLE, WILDCARD_DISPOSABLE } = await jiti.import(new URL("../src/disposable-policy.ts", import.meta.url).href);
const { checkMx } = await jiti.import(new URL("../src/mx.ts", import.meta.url).href);

const args = process.argv.slice(2);
const reviewIndex = args.indexOf("--review");
const review = reviewIndex >= 0;
const topN = review && /^\d+$/.test(args[reviewIndex + 1] ?? "") ? Number(args[reviewIndex + 1]) : 100_000;

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
const text = await response.text();
const LABEL = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;
// Only the mailbox providers: a NOT_TYPOS domain may well be disposable (e-mail.com is).
const providers = new Set(PROVIDER_DOMAINS);
const never = Object.keys(NEVER_DISPOSABLE);
const skipped = [];
const domains = new Set();
for (const line of text.split("\n")) {
  const domain = line.trim().toLowerCase().replace(/\.$/, "");
  if (!domain || domain.startsWith("#")) continue;
  const labels = domain.split(".");
  if (labels.length < 2 || !labels.every((label) => LABEL.test(label))) {
    skipped.push(`${domain} (not a host name)`);
    continue;
  }
  // A provider equal to the entry or below it would be refused by the parent match.
  const provider = [...providers].find((p) => p === domain || p.endsWith(`.${domain}`));
  if (provider) {
    skipped.push(`${domain} (would cover provider ${provider})`);
    continue;
  }
  const company = never.find((n) => domain === n || domain.endsWith(`.${n}`));
  if (company) {
    skipped.push(`${domain} (NEVER_DISPOSABLE: ${NEVER_DISPOSABLE[company]})`);
    continue;
  }
  domains.add(domain);
}
const sorted = [...domains].sort();
if (sorted.length < 1000) throw new Error(`only ${sorted.length} domains parsed; refusing to write a short list`);

const out = `/**
 * Disposable (throwaway) email domains, from the disposable-email-domains
 * project (https://github.com/disposable-email-domains/disposable-email-domains,
 * CC0 1.0, thanks to its contributors). ${sorted.length} domains, with the
 * reviewed exceptions of disposable-policy.ts left out.
 * Generated by scripts/update-disposable.mjs; do not edit by hand.
 */
export const DISPOSABLE_DOMAIN_TEXT: string = ${JSON.stringify(sorted.join("\n"))};
`;
writeFileSync(new URL("../src/disposable-list.ts", import.meta.url), out);
console.log(`wrote ${sorted.length} domains`);
for (const line of skipped) console.log(`skipped: ${line}`);

const wildcards = args.includes("--wildcards");

/** Tranco ranks, downloaded at run time, never committed. */
async function trancoRanks(size) {
  const idResponse = await fetch("https://tranco-list.eu/top-1m-id");
  if (!idResponse.ok) throw new Error(`tranco id: HTTP ${idResponse.status}`);
  const id = (await idResponse.text()).trim();
  const listResponse = await fetch(`https://tranco-list.eu/download/${encodeURIComponent(id)}/${size}`);
  if (!listResponse.ok) throw new Error(`tranco list ${id}: HTTP ${listResponse.status}`);
  const rank = new Map();
  for (const row of (await listResponse.text()).split("\n")) {
    const [r, d] = row.trim().split(",");
    if (r && d) rank.set(d.toLowerCase(), Number(r));
  }
  return { id, rank };
}

const matching = (d) => (Object.hasOwn(WILDCARD_DISPOSABLE, d) ? "wildcard: subdomains too" : "exact name only");

if (review) {
  const { id, rank } = await trancoRanks(topN);
  const ranked = sorted.filter((d) => rank.has(d)).sort((a, b) => rank.get(a) - rank.get(b));
  console.log(`\nReview: ${ranked.length} list entries in the Tranco top ${topN} (list ${id}); those with their own MX:\n`);
  console.log("| rank | domain | MX | matching |");
  console.log("|---|---|---|---|");
  for (let i = 0; i < ranked.length; i += 8) {
    const batch = ranked.slice(i, i + 8);
    const results = await Promise.all(batch.map((d) => checkMx(d, { cache: null, timeoutMs: 5000 })));
    for (const [j, d] of batch.entries()) {
      const r = results[j];
      if (r.kind !== "deliverable" || r.via !== "mx") continue;
      console.log(`| ${rank.get(d)} | ${d} | ${r.hosts.slice(0, 2).join(", ")} | ${matching(d)} |`);
    }
  }
}

if (wildcards) {
  const { id, rank } = await trancoRanks(1_000_000);
  const label = `zq${Math.random().toString(36).slice(2, 10)}`;
  const found = [];
  for (let i = 0; i < sorted.length; i += 32) {
    const batch = sorted.slice(i, i + 32);
    const results = await Promise.all(batch.map((d) => checkMx(`${label}.${d}`, { cache: null, timeoutMs: 6000 })));
    for (const [j, d] of batch.entries()) {
      const r = results[j];
      if (r.kind === "deliverable" && r.via === "mx") found.push({ d, hosts: r.hosts });
    }
  }
  const ranked = found.filter((f) => rank.has(f.d)).sort((a, b) => rank.get(a.d) - rank.get(b.d));
  console.log(`\nWildcard MX: ${found.length} of ${sorted.length} entries answer an MX at ${label}.<entry>; ${ranked.length} rank in Tranco (list ${id}):\n`);
  console.log("| rank | domain | MX below it | matching |");
  console.log("|---|---|---|---|");
  for (const f of ranked) console.log(`| ${rank.get(f.d)} | ${f.d} | ${f.hosts.slice(0, 2).join(", ")} | ${matching(f.d)} |`);
  const stale = Object.keys(WILDCARD_DISPOSABLE).filter((d) => !found.some((f) => f.d === d));
  if (stale.length > 0) console.log(`\nWILDCARD_DISPOSABLE entries with no wildcard MX this run (review): ${stale.join(", ")}`);
}
